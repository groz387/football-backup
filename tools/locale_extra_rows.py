"""Extra-key rows in EXTRA_UI insertion order. zip() in the generator."""
from __future__ import annotations

from recap.locales._extras import EXTRA_UI

KEYS = list(EXTRA_UI)


def pack(rows: list[str]) -> dict[str, str]:
    if len(rows) != len(KEYS):
        raise ValueError(f"want {len(KEYS)} rows, got {len(rows)}")
    return dict(zip(KEYS, rows))


